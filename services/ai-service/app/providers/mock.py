"""Deterministic mock provider for CI, tests and dry runs (FR-WF-010).

Produces schema-valid outputs derived from the request so end-to-end workflows
can run without model credits. It never makes network calls. Test-only knob:
`intent.mock_behavior` = "invalid_once" | "invalid_always".
"""

from __future__ import annotations

import hashlib
import json
import math
import re
from typing import Any

from ..prompts import BuiltPrompt, estimate_tokens
from ..schemas import EvidenceItem, GenerateRequest, ProviderHealth
from .base import EmbeddingResult, RawGeneration

MOCK_MODEL = "mock-deterministic"


def _paths(evidence: list[EvidenceItem], included: list[str]) -> list[str]:
    allowed = set(included)
    seen: list[str] = []
    for e in evidence:
        if e.id in allowed and e.path not in seen:
            seen.append(e.path)
    return seen


def _ctx_list(ctx: dict[str, Any] | None, *keys: str) -> list[Any]:
    cur: Any = ctx or {}
    for k in keys:
        cur = cur.get(k) if isinstance(cur, dict) else None
    return cur if isinstance(cur, list) else []


class MockProvider:
    name = "mock"
    mode = "mock"

    def __init__(self) -> None:
        self._invalid_served: set[str] = set()

    async def generate(
        self,
        prompt: BuiltPrompt,
        request: GenerateRequest,
        max_output_tokens: int,
        timeout_seconds: float,
        repair_note: str | None,
    ) -> RawGeneration:
        behavior = request.intent.get("mock_behavior")
        key = hashlib.sha256(prompt.user.encode()).hexdigest()
        if behavior == "invalid_always" or (behavior == "invalid_once" and key not in self._invalid_served):
            self._invalid_served.add(key)
            text = '{"unexpected": "not the required schema"}'
        else:
            text = json.dumps(self._output(request, prompt))
        return RawGeneration(
            text=text, model=MOCK_MODEL, input_tokens=prompt.input_tokens_estimate, output_tokens=estimate_tokens(text)
        )

    def _output(self, req: GenerateRequest, prompt: BuiltPrompt) -> dict[str, Any]:
        included = prompt.evidence_included
        ev = [e for e in req.evidence if e.id in set(included)]
        paths = _paths(req.evidence, included)
        title = str(
            req.intent.get("objective_title") or req.intent.get("title") or req.intent.get("question") or "the task"
        )[:200]
        if req.task == "repository_qa":
            if not ev:
                return {
                    "answer": "The indexed evidence does not contain enough information to answer this question.",
                    "citations": [],
                    "limitations": ["No relevant evidence was retrieved."],
                    "insufficient_evidence": True,
                }
            top = ev[:3]
            parts = [f"{e.path} (lines {e.start_line}-{e.end_line})" for e in top]
            return {
                "answer": f"[mock] The most relevant code for '{title}' is in " + ", ".join(parts) + ".",
                "citations": [{"evidence_id": e.id, "supports": f"Relevant code in {e.path}"} for e in top],
                "limitations": ["Generated by the deterministic mock provider; not a model answer."],
                "insufficient_evidence": False,
            }
        if req.task == "investigation":
            return {
                "summary": f"[mock] Investigation of '{title}' based on {len(ev)} evidence item(s).",
                "findings": [
                    {"claim": f"{e.path} is relevant to the task.", "evidence_ids": [e.id], "kind": "observed"}
                    for e in ev[:3]
                ],
                "hypotheses": ["[mock] The behaviour originates in the most relevant module."] if ev else [],
                "unknowns": [] if ev else ["No relevant evidence was retrieved."],
                "candidate_files": paths[:4],
            }
        if req.task == "planning":
            files = [str(p) for p in _ctx_list(req.context, "investigation", "candidate_files")][:4] or paths[:2]
            return {
                "objective": f"[mock] Address: {title}",
                "assumptions": ["The indexed snapshot reflects the base branch."],
                "steps": [
                    {
                        "id": f"step-{i + 1}",
                        "description": f"Update {f}",
                        "files": [f],
                        "verification": ["Run the test profile"],
                    }
                    for i, f in enumerate(files)
                ]
                or [
                    {
                        "id": "step-1",
                        "description": "Investigate further; no candidate files were identified.",
                        "files": [],
                        "verification": [],
                    }
                ],
                "files_to_modify": files,
                "tests": ["existing tests"],
                "risks": ["[mock] Behaviour change in dependent modules."],
                "out_of_scope": ["Unrelated refactoring"],
            }
        if req.task in ("patch", "repair"):
            files = _ctx_list(req.context, "files")
            changes: list[dict[str, Any]] = []
            for f in files[:4]:
                if (
                    not isinstance(f, dict)
                    or not isinstance(f.get("path"), str)
                    or not isinstance(f.get("content"), str)
                ):
                    continue
                marker = "#" if f["path"].endswith(".py") else "//"
                note = "repair" if req.task == "repair" else "change"
                changes.append(
                    {
                        "path": f["path"],
                        "action": "modify",
                        "content": f["content"].rstrip("\n") + f"\n{marker} anvaya mock {note}: {title[:80]}\n",
                        "explanation": "Deterministic mock change.",
                    }
                )
            if not changes:
                return {
                    "summary": "[mock] No approved files were provided.",
                    "changes": [
                        {
                            "path": "ANVAYA_MOCK.md",
                            "action": "create",
                            "content": f"# {title}\n",
                            "explanation": "Mock placeholder.",
                        }
                    ],
                    "plan_revision_needed": True,
                }
            return {"summary": f"[mock] Implemented: {title}", "changes": changes, "plan_revision_needed": False}
        if req.task == "review":
            changed = _ctx_list(req.context, "changed_files")
            path = changed[0] if changed and isinstance(changed[0], str) else (paths[0] if paths else "README.md")
            return {
                "summary": "[mock] Review completed; no blocking issues identified by the mock reviewer.",
                "findings": [
                    {
                        "severity": "info",
                        "file_path": path,
                        "start_line": 1,
                        "end_line": 1,
                        "title": "Mock review note",
                        "rationale": "The deterministic mock reviewer does not analyse code.",
                        "evidence": ["diff"],
                        "confidence": "low",
                        "suggested_action": None,
                    }
                ],
            }
        return {
            "summary": "[mock] Verification results summarised.",
            "likely_causes": [],
            "suggested_next_steps": ["Inspect the failing profile output."],
        }

    async def health(self) -> ProviderHealth:
        return ProviderHealth(provider="mock", mode="mock", available=True, models=[MOCK_MODEL])


class MockEmbeddingProvider:
    """Deterministic bag-of-words embeddings: lexically similar text → similar vectors."""

    name = "mock"

    def __init__(self, dimension: int) -> None:
        self.dimension = dimension

    def _vector(self, text: str) -> list[float]:
        v = [0.0] * self.dimension
        spaced = re.sub(r"([a-z])([A-Z])", r"\1 \2", text).lower()
        for term in re.split(r"[^a-z0-9]+", spaced):
            if len(term) >= 2:
                h = hashlib.sha1(term.encode(), usedforsecurity=False).digest()
                v[int.from_bytes(h[:2], "big") % self.dimension] += 1.0
        norm = math.sqrt(sum(x * x for x in v)) or 1.0
        return [x / norm for x in v]

    async def embed(self, texts: list[str], input_type: str) -> EmbeddingResult:
        return EmbeddingResult(
            model="mock-embed", model_version="1", vectors=[self._vector(t) for t in texts], input_tokens=0
        )

    async def health(self) -> ProviderHealth:
        return ProviderHealth(provider="mock", mode="mock", available=True, models=["mock-embed"])
