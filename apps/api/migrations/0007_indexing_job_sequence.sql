-- 0007_indexing_job_sequence.sql — order indexing jobs by insertion, not by wall clock.
--
-- "Latest job" was chosen by created_at, which comes from the database clock. A clock that steps
-- backwards (VM time resync; NTP step) made a newer job look older, so index-status reported the
-- previous job's outcome. An identity column is monotonic regardless of the clock. Existing rows
-- are numbered in their current physical order, which is fine for historical jobs.

ALTER TABLE indexing_jobs
  ADD COLUMN seq bigint GENERATED BY DEFAULT AS IDENTITY;

CREATE INDEX idx_indexing_jobs_repo_seq ON indexing_jobs (repository_id, seq DESC);
